/**
 * 異体字セレクタ（VS1〜16・VS17〜256）か. db.js の isVariationSelector と同じ。
 * このファイルは scripts/add_confusable.mjs が単独で読み込むので、ほかのモジュールを import しない
 */
const isVariationSelector = (cp) => (cp >= 0xfe00 && cp <= 0xfe0f) || (cp >= 0xe0100 && cp <= 0xe01ef);

// 高速ルックアップ用のインデックスマップ
/** @type {Map<string, ConfusableGroup[]>} */
const charToGroups = new Map();

for (const group of CONFUSABLE_GROUPS) {
  for (const ch of group.chars) {
    if (!charToGroups.has(ch)) charToGroups.set(ch, []);
    charToGroups.get(ch).push(group);
  }
}

/**
 * ある文字に関連する混同・異構字グループを取得する.
 * @param {string} char
 * @returns {Array<{ group: ConfusableGroup, others: string[] }>}
 */
export function getConfusablesForChar(char) {
  const groups = charToGroups.get(char) ?? [];
  return groups.map((group) => ({
    group,
    others: group.chars.filter((c) => c !== char),
  }));
}

/**
 * 検索クエリ（単語・苗字など）から、混同しやすい字・異構字を置き換えた別の表記候補を生成する.
 * 例: "中島" → ["中嶋", "中嶌"]
 *     "柳田" → ["栁田"]
 *     "山崎" → ["山﨑", "山嵜", "山碕"]
 *     "柿落とし" → ["杮落とし"]
 * @param {string} word
 * @returns {Array<{ word: string, from: string, to: string, type: 'variant' | 'confusable', name: string }>}
 */
export function getWordVariantSuggestions(word) {
  if (!word || word.length > 8) return []; // 長すぎるクエリは除外
  const chars = [...word];
  const suggestions = [];
  const seen = new Set([word]);

  for (let i = 0; i < chars.length; i++) {
    const ch = chars[i];
    const rels = getConfusablesForChar(ch);
    // 後ろの異体字セレクタは元の字の字形を選ぶものなので、別の字に置き換えるときは外す（辺+E010F のような列は無い）
    const rest = i + 1 < chars.length && isVariationSelector(chars[i + 1].codePointAt(0)) ? i + 2 : i + 1;
    for (const { group, others } of rels) {
      for (const other of others) {
        const candidate = chars.slice(0, i).join('') + other + chars.slice(rest).join('');
        if (!seen.has(candidate)) {
          seen.add(candidate);
          suggestions.push({
            word: candidate,
            from: ch,
            to: other,
            type: group.type,
            name: group.name,
          });
        }
      }
    }
  }

  return suggestions;
}
